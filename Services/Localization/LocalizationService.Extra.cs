    private static readonly Regex EnglishWord = new("[a-z]{3,}", RegexOptions.Compiled);

    private static readonly Lazy<Dictionary<string, string>> ReverseToEnglish = new(() =>
    {
        var map = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var source in new[] { EnToKa, UiEnToKa })
            foreach (var (en, ka) in source)
                if (GeorgianLetters.IsMatch(ka) && !GeorgianLetters.IsMatch(en))
                    map.TryAdd(ka, en);
        return map;
    });

    private static readonly Lazy<Dictionary<string, string>> ReverseToGeorgian = new(() =>
    {
        var map = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var source in new[] { ExtraKaToEn, MotoKaToEn, ExtendedKaToEn, KaToEn, UiKaToEn })
            foreach (var (ka, en) in source)
                // Only real English phrases; short codes (VIN, ECU, PRO …) stay as they are.
                if (GeorgianLetters.IsMatch(ka) && !GeorgianLetters.IsMatch(en) && EnglishWord.IsMatch(en))
                    map.TryAdd(en, ka);
        return map;
    });

    private static readonly Lazy<(Regex Pattern, string Target)[]> ExtraToEnglishTemplates = new(() =>
        BuildTemplates(ExtraTemplateItems.Select(item => (item.Ka, item.En)).ToArray()));

    private static readonly Lazy<(Regex Pattern, string Target)[]> ExtraToGeorgianTemplates = new(() =>
        BuildTemplates(ExtraTemplateItems.Select(item => (item.En, item.Ka)).ToArray()));

    /// <summary>Georgian text → English from the extra pairs or the reversed English → Georgian dictionaries.</summary>
    private static string? LookupExtraEnglish(string text) =>
        ExtraKaToEn.TryGetValue(text, out var en) ? en
        : ReverseToEnglish.Value.TryGetValue(text, out var reversed) ? reversed
        : null;

    /// <summary>English text → Georgian from the reversed Georgian → English dictionaries.</summary>
    private static string? LookupExtraGeorgian(string text) =>
        ReverseToGeorgian.Value.TryGetValue(text, out var ka) ? ka : null;
