    [Fact]
    public void Honda_RequestsAre29Bit_AndLoadTestSupported()
    {
        Assert.True(HondaHybridBattery.Cells.Ext29);
        Assert.Equal("18DA01F1 222028", HondaHybridBattery.Cells.Label);
        Assert.True(HvPackProtocol.SupportsLoadTest(HvPackKind.HondaHybrid));
        Assert.False(HondaHybridBattery.IsHondaHybrid("Honda", "Civic", 2018));
        Assert.True(HondaHybridBattery.IsHondaHybrid("Honda", "CR-V", 2024));
    }

    [Fact]
    public void JaguarIPace_CellsTemperatureVoltageSocHealth()
    {
        Assert.Equal(3.682, JaguarIPaceBattery.DecodeCell(Data("7EC056249030E62", JaguarIPaceBattery.MaximumCell))!.Value, 3);
        Assert.Equal(3.672, JaguarIPaceBattery.DecodeCell(Data("7EC056249040E58", JaguarIPaceBattery.MinimumCell))!.Value, 3);
        Assert.Equal(10.5, JaguarIPaceBattery.DecodeTemperature(Data("7EC0462490765", JaguarIPaceBattery.Temperature))!.Value, 1);
        Assert.Equal(397.43, JaguarIPaceBattery.DecodeVoltage(Data("7EC0562490F9B3F", JaguarIPaceBattery.Voltage))!.Value, 2);
        Assert.Equal(24.59, JaguarIPaceBattery.DecodeSoc(Data("7EC05624910099B", JaguarIPaceBattery.Soc))!.Value, 2);
        Assert.Equal(88.5, JaguarIPaceBattery.DecodeSoh(Data("7EC04624918B1", JaguarIPaceBattery.Health))!.Value, 1);
        Assert.True(JaguarIPaceBattery.IsIPace("Jaguar", "I-PACE"));
        Assert.False(JaguarIPaceBattery.IsIPace("Jaguar", "XF"));
        Assert.False(HvPackProtocol.SupportsLoadTest(HvPackKind.JaguarIPace));
    }

    [Fact]
    public void MgZsEv_PackAndModule()
    {
        Assert.Equal(51.1, MgZsEvBattery.DecodeSoc(Data("7890562B04601FF", MgZsEvBattery.Soc))!.Value, 1);
        Assert.Equal(383.75, MgZsEvBattery.DecodeVoltage(Data("7890562B04205FF", MgZsEvBattery.Voltage))!.Value, 2);

        var module = MgZsEvBattery.DecodeModule(Data("7ED100A62B009122712\n7ED212A8B8B90AAAAAA", MgZsEvBattery.Modules[1]));
        Assert.NotNull(module);
        Assert.Equal(3.3235, module!.MinVolts, 4);
        Assert.Equal(3.325, module.MaxVolts, 4);
        Assert.Equal(29.5, module.MinTemperature, 1);
        Assert.Equal(29.5, module.MaxTemperature, 1);
        Assert.True(MgZsEvBattery.IsZsEv("MG", "ZS EV"));
        Assert.False(MgZsEvBattery.IsZsEv("MG", "MG4"));
    }

